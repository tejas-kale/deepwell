#!/bin/bash
# Builds DeepwellPreprocessing.js for the iOS Share Extension (ticket 18): the Safari extension's extraction files,
# unchanged, plus Extensions/MobileShareExtension/preprocess-shim.js, inside one function that returns the
# ExtensionPreprocessingJS object Safari calls. One JS codebase: edit the Safari extension's files, not this output.
# Run by Xcode (DeepwellMobileShare's build phase) with SRCROOT and an output path; or by hand:
#   scripts/build-share-preprocessing.sh <output.js>
set -euo pipefail
root="${SRCROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
out="${1:-${SCRIPT_OUTPUT_FILE_0:?pass an output path}}"
res="$root/Extensions/SafariExtension/Resources"
mkdir -p "$(dirname "$out")"
{
  echo "// Generated by scripts/build-share-preprocessing.sh. Do not edit."
  echo "var ExtensionPreprocessingJS = (function () {"
  # Shadow any page global named \`module\`, so the files' node-only export branches never run.
  echo "var module;"
  for f in readability.js turndown.js turndown-plugin-gfm.js extract.js youtube.js; do
    echo ";// ---- $f"
    cat "$res/$f"
    echo
  done
  cat "$root/Extensions/MobileShareExtension/preprocess-shim.js"
  echo "})();"
} > "$out.tmp"
mv "$out.tmp" "$out"
